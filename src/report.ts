import { RULES } from "./dpdp.js";
import { CLASS_LABEL } from "./fields.js";
import { renderHtml } from "./html.js";
import type { Finding, ScanResult, Severity } from "./types.js";

export type Format = "pretty" | "json" | "sarif" | "markdown" | "html";

export function countBySeverity(findings: Finding[]): Record<Severity, number> {
  const counts: Record<Severity, number> = { high: 0, medium: 0, low: 0 };
  for (const f of findings) counts[f.severity]++;
  return counts;
}

function pretty(result: ScanResult, color: boolean): string {
  const paint = (code: number, text: string) => (color ? `\u001b[${code}m${text}\u001b[0m` : text);
  const severityColor: Record<Severity, number> = { high: 31, medium: 33, low: 36 };
  const lines: string[] = [];
  for (const f of result.findings) {
    const rule = RULES[f.ruleId]!;
    lines.push(
      `${paint(severityColor[f.severity], f.severity.toUpperCase().padEnd(6))} ${paint(1, f.ruleId)}  ${f.path}:${f.line}`,
      `       ${f.message}  ${paint(2, `[${rule.citation}]`)}`,
    );
    if (f.ai) {
      lines.push(`       ${paint(35, `AI ${f.ai.verdict.replace("_", " ")} (${Math.round(f.ai.confidence * 100)}%)`)}: ${f.ai.explanation}`);
      if (f.ai.fix) lines.push(`       ${paint(32, "fix")}: ${f.ai.fix.split("\n").join("\n            ")}`);
    }
    lines.push("");
  }
  const counts = countBySeverity(result.findings);
  const columns = result.inventory.reduce((n, t) => n + t.columns.length, 0);
  lines.push(
    `${result.filesScanned} files scanned. ${result.findings.length} findings: ${counts.high} high, ${counts.medium} medium, ${counts.low} low.`,
    `Data inventory: ${columns} personal data columns in ${result.inventory.length} tables.` +
      (result.thirdParties.length ? ` Third parties receiving personal data: ${result.thirdParties.join(", ")}.` : ""),
    result.ai.used ? `AI review: ${result.ai.model}${result.ai.note ? ` (${result.ai.note})` : ""}.` : (result.ai.note ?? "AI review: off."),
    "Findings are pointers for review, not a compliance determination.",
  );
  return lines.join("\n");
}

function sarif(result: ScanResult): string {
  const level: Record<Severity, string> = { high: "error", medium: "warning", low: "note" };
  const used = [...new Set(result.findings.map((f) => f.ruleId))].sort();
  return JSON.stringify(
    {
      $schema: "https://json.schemastore.org/sarif-2.1.0.json",
      version: "2.1.0",
      runs: [
        {
          tool: {
            driver: {
              name: "dpdp-scan",
              informationUri: "https://github.com/rohitguta2432/dpdp-scan",
              rules: used.map((id) => {
                const rule = RULES[id]!;
                return {
                  id,
                  name: rule.name,
                  shortDescription: { text: rule.title },
                  fullDescription: { text: `${rule.title}. Reference: ${rule.citation}.` },
                  help: { text: `${rule.help} Reference: ${rule.citation}.` },
                };
              }),
            },
          },
          results: result.findings.map((f) => ({
            ruleId: f.ruleId,
            level: level[f.severity],
            message: { text: `${f.message}. Reference: ${RULES[f.ruleId]!.citation}.${f.ai ? ` AI: ${f.ai.explanation}` : ""}` },
            locations: [
              {
                physicalLocation: {
                  artifactLocation: { uri: f.path, uriBaseId: "%SRCROOT%" },
                  region: { startLine: f.line },
                },
              },
            ],
            partialFingerprints: { dpdpScan: `${f.ruleId}:${f.path}:${f.dataClass}:${f.detail ?? ""}` },
            properties: { dataClass: f.dataClass, ...(f.ai ? { aiVerdict: f.ai.verdict, aiConfidence: f.ai.confidence } : {}) },
          })),
        },
      ],
    },
    null,
    2,
  );
}

const cell = (text: string) => text.replace(/\|/g, "\\|").replace(/\n/g, " ");

/** Markdown data inventory: what personal data exists, where, and how it is handled. */
export function markdown(result: ScanResult): string {
  const out: string[] = [
    "# Personal data inventory",
    "",
    `Generated by dpdp-scan from ${result.filesScanned} files. Review before relying on it; a code scan cannot see data that is not in the repository.`,
    "",
  ];
  if (!result.inventory.length) out.push("No personal data columns were found in SQL, Prisma, JPA, or Python ORM schemas.", "");
  for (const table of result.inventory) {
    out.push(`## ${table.table}`, "", `Defined in \`${table.path}\`. Erasure path found: ${table.hasErasurePath ? "yes" : "**no**"}.`);
    if (table.purpose) out.push(`Likely purpose (AI inferred): ${table.purpose}`);
    if (table.retention) out.push(`Retention suggestion (AI inferred): ${table.retention}`);
    out.push("", "| Column | Category | Type | Protection visible | Location |", "| --- | --- | --- | --- | --- |");
    for (const c of table.columns) {
      out.push(`| ${cell(c.column)} | ${CLASS_LABEL[c.dataClass!]} | ${cell(c.type)} | ${c.protected ? "yes" : "no"} | ${c.path}:${c.line} |`);
    }
    out.push("");
  }
  out.push("## Third parties receiving personal data", "");
  out.push(result.thirdParties.length ? result.thirdParties.map((v) => `- ${v}`).join("\n") : "None detected.", "");
  out.push("## Findings", "", "| Severity | Rule | Location | Finding | Reference |", "| --- | --- | --- | --- | --- |");
  for (const f of result.findings) {
    out.push(`| ${f.severity} | ${f.ruleId} | ${f.path}:${f.line} | ${cell(f.message)} | ${RULES[f.ruleId]!.citation} |`);
  }
  return `${out.join("\n")}\n`;
}

export function render(result: ScanResult, format: Format, color = false): string {
  switch (format) {
    case "json":
      return JSON.stringify({ ...result, rules: RULES }, null, 2);
    case "sarif":
      return sarif(result);
    case "markdown":
      return markdown(result);
    case "html":
      return renderHtml(result);
    default:
      return pretty(result, color);
  }
}
